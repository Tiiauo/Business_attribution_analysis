"""Export the shared Python schemas and the TypeScript types from one source."""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))
from app import contracts  # noqa: E402
from app.runtime import ConfigState, RuntimeBundle  # noqa: E402

MODELS = (
    contracts.UserInfo,
    contracts.ErrorResponse,
    contracts.Evidence,
    contracts.SubscriptionReady,
    contracts.TaskEvent,
    contracts.SendRequest,
    contracts.HistoryPage,
    contracts.AttachmentPage,
    contracts.TaskSnapshot,
    contracts.AnalysisOutput,
    contracts.ResultInfo,
    ConfigState,
    RuntimeBundle,
)


def ts_type(schema):
    if "$ref" in schema:
        return schema["$ref"].split("/")[-1]
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    if "anyOf" in schema:
        return " | ".join(ts_type(value) for value in schema["anyOf"])
    if "oneOf" in schema:
        return " | ".join(ts_type(value) for value in schema["oneOf"])
    kind = schema.get("type")
    if kind == "array":
        return f"Array<{ts_type(schema['items'])}>"
    if kind == "object":
        fields = [
            f"{json.dumps(key)}{'' if key in schema.get('required', []) else '?'}: {ts_type(value)}"
            for key, value in schema.get("properties", {}).items()
        ]
        if fields:
            return "{ " + "; ".join(fields) + " }"
        additional = schema.get("additionalProperties")
        return f"Record<string, {ts_type(additional)}>" if isinstance(additional, dict) else "Record<string, unknown>"
    return {"string": "string", "integer": "number", "number": "number", "null": "null", "boolean": "boolean"}.get(
        kind, "unknown"
    )


def outputs():
    schemas = {model.__name__: model.model_json_schema(by_alias=True) for model in MODELS}
    definitions = {}
    for schema in schemas.values():
        definitions.update(schema.get("$defs", {}))
    types = "// Generated by scripts/export-contracts.py; edit backend/app/contracts.py.\n"
    for name, schema in {**definitions, **schemas}.items():
        types += f"export type {name} = {ts_type(schema)};\n"
    return {
        ROOT / "docs/contracts/schemas.json": json.dumps(schemas, ensure_ascii=False, indent=2) + "\n",
        ROOT / "frontend/src/contracts.ts": types,
    }


if __name__ == "__main__":
    for path, content in outputs().items():
        if "--check" in sys.argv:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                raise SystemExit(f"Contract export out of date: {path.name}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
    print("Shared contracts are current.")
